// Представление текста дельт в том виде, в каком он лежит в собранном бандле.
//
// Апстрим публикуется уже собранным, и два вида кода выглядят в нём по-разному:
// CSS встроен строковым литералом `style_default` (переводы строк экранированы
// как \n), а JS — обычным текстом с отступом модуля в четыре пробела. Дельты
// пишутся в человеческом виде, а эти помощники приводят их к байтам бандла.

// CSS внутри строкового литерала: экранируем обрамляющую кавычку, обратный слэш
// и переводы строк — ровно так это делает сборщик апстрима (.css text-loader).
export const cssText = (text) =>
  text
    .replace(/\r\n/g, '\n')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')

// Код бандла: убираем общий минимальный отступ и ставим нужный (по умолчанию —
// четыре пробела уровня модуля). Пустые строки остаются пустыми, без хвостов.
export const codeText = (text, indent = 4) => {
  const lines = text.replace(/\r\n/g, '\n').split('\n')
  const widths = lines.filter((line) => line.trim() !== '').map((line) => /^ */.exec(line)[0].length)
  const base = widths.length === 0 ? 0 : Math.min(...widths)
  return lines
    .map((line) => (line.trim() === '' ? '' : ' '.repeat(indent) + line.slice(base)))
    .join('\n')
}
